GAP = 1


def _glyph(ch: str) -> list[str]:
    return GLYPHS.get(ch, GLYPHS["?"])


def text_width(text: str) -> int:
    return max(0, sum(len(_glyph(ch)[0]) + GAP for ch in text.upper()) - GAP)


def draw_text(c: Canvas, x: int, y: int, text: str, color: str) -> None:
    for ch in text.upper():
        g = _glyph(ch)
        c.stamp(x, y, g, {"#": color})
        x += len(g[0]) + GAP


def draw_text_centered(c: Canvas, cx: int, y: int, text: str, color: str) -> None:
    draw_text(c, cx - text_width(text) // 2, y, text, color)


